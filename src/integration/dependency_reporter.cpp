DependencyReporter::DependencyReporter(const std::string& cache_dir)
    : cache_dir_(cache_dir) {
    default_export_path_ = cache_dir + "/reports";
    initialized_ = initialize();
}

DependencyReporter::~DependencyReporter() = default;

bool DependencyReporter::initialize() {
    if (!ensureDirectoryExists(cache_dir_)) {
        return false;
    }

    if (!ensureDirectoryExists(default_export_path_)) {
        return false;
    }

    return loadDefaultTemplates();
}

DependencyReport DependencyReporter::generateDependencyReport(const std::vector<DependencyInfo>& dependencies) const {
    DependencyReport report;
    report.report_id = generateReportID();
    report.generated_timestamp = getCurrentTimestamp();
    report.generated_by = "DependencyReporter v1.0.0";
    report.total_dependencies = static_cast<int>(dependencies.size());
    report.dependencies = dependencies;

    // Calculate statistics
    for (const auto& dep : dependencies) {
        if (dep.status == "active") {
            report.active_dependencies++;
        } else if (dep.status == "outdated") {
            report.outdated_dependencies++;
        }

        if (!dep.license.empty()) {
            report.license_types[dep.license]++;
        }

        if (!dep.source_type.empty()) {
            report.source_types[dep.source_type]++;
        }

        if (!dep.security_issues.empty()) {
            report.security_issues += static_cast<int>(dep.security_issues.size());
        }
    }

    // Generate recommendations
    report.recommendations = generateRecommendations(dependencies);

    // Add metadata
    report.metadata["generator_version"] = getReportVersion();
    report.metadata["os"] = "Linux";
    report.metadata["generation_time_ms"] = "0";

    return report;
}

json DependencyReporter::generateJSONReport(const std::vector<DependencyInfo>& dependencies) const {
    auto report = generateDependencyReport(dependencies);

    json json_report;
    json_report["report_id"] = report.report_id;
    json_report["generated_timestamp"] = report.generated_timestamp;
    json_report["generated_by"] = report.generated_by;
    json_report["total_dependencies"] = report.total_dependencies;
    json_report["active_dependencies"] = report.active_dependencies;
    json_report["outdated_dependencies"] = report.outdated_dependencies;
    json_report["security_issues"] = report.security_issues;
    json_report["license_types"] = report.license_types;
    json_report["source_types"] = report.source_types;
    json_report["recommendations"] = report.recommendations;
    json_report["metadata"] = report.metadata;

    // Add dependencies
    json deps_array = json::array();
    for (const auto& dep : dependencies) {
        deps_array.push_back(dependencyToJSON(dep));
    }
    json_report["dependencies"] = deps_array;

    return json_report;
}

std::string DependencyReporter::generateMarkdownReport(const std::vector<DependencyInfo>& dependencies) const {
    auto report = generateDependencyReport(dependencies);

    std::ostringstream markdown;

    markdown << "# Dependency Report\n\n";
    markdown << "**Report ID:** " << report.report_id << "\n";
    markdown << "**Generated:** " << report.generated_timestamp << "\n";
    markdown << "**Generated by:** " << report.generated_by << "\n\n";

    // Summary section
    markdown << "## Summary\n\n";
    markdown << "- **Total Dependencies:** " << report.total_dependencies << "\n";
    markdown << "- **Active Dependencies:** " << report.active_dependencies << "\n";
    markdown << "- **Outdated Dependencies:** " << report.outdated_dependencies << "\n";
    markdown << "- **Security Issues:** " << report.security_issues << "\n\n";

    // License types
    if (!report.license_types.empty()) {
        markdown << "### License Distribution\n\n";
        for (const auto& [license, count] : report.license_types) {
            markdown << "- **" << license << ":** " << count << "\n";
        }
        markdown << "\n";
    }

    // Source types
    if (!report.source_types.empty()) {
        markdown << "### Source Distribution\n\n";
        for (const auto& [source, count] : report.source_types) {
            markdown << "- **" << source << ":** " << count << "\n";
        }
        markdown << "\n";
    }

    // Dependencies table
    markdown << "## Dependencies\n\n";
    markdown << "| Name | Version | Status | License | Source | Compatibility |\n";
    markdown << "|------|---------|--------|---------|--------|---------------|\n";

    for (const auto& dep : dependencies) {
        markdown << "| " << dep.name
                 << " | " << dep.version
                 << " | " << dep.status
                 << " | " << dep.license
                 << " | " << dep.source_type
                 << " | " << formatCompatibilityScore(dep.compatibility_score)
                 << " |\n";
    }
    markdown << "\n";

    // Recommendations
    if (!report.recommendations.empty()) {
        markdown << "## Recommendations\n\n";
        for (size_t i = 0; i < report.recommendations.size(); ++i) {
            markdown << (i + 1) << ". " << report.recommendations[i] << "\n";
        }
        markdown << "\n";
    }

    return markdown.str();
}

