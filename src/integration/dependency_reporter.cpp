DependencyMetrics DependencyReporter::generateDependencyMetrics(const std::vector<DependencyInfo>& dependencies) const {
    DependencyMetrics metrics;
    metrics.total_dependencies = static_cast<int>(dependencies.size());

    std::vector<double> compatibility_scores;

    for (const auto& dep : dependencies) {
        if (dep.status == "active") {
            metrics.active_dependencies++;
        } else if (dep.status == "outdated") {
            metrics.outdated_dependencies++;
        }

        if (!dep.security_issues.empty()) {
            metrics.security_issues += static_cast<int>(dep.security_issues.size());
        }

        if (dep.compatibility_score > 0) {
            compatibility_scores.push_back(dep.compatibility_score);
        }

        // Track recent and old dependencies
        if (!dep.last_update.empty()) {
            if (metrics.most_recent_updates.size() < 5) {
                metrics.most_recent_updates.push_back(dep.name + " (" + dep.last_update + ")");
            }
        }
    }

    // Calculate average compatibility score
    if (!compatibility_scores.empty()) {
        metrics.average_compatibility_score = std::accumulate(compatibility_scores.begin(),
                                                            compatibility_scores.end(), 0.0) /
                                            compatibility_scores.size();
    }

    metrics.license_types = calculateLicenseDistribution(dependencies);
    metrics.source_types = calculateSourceDistribution(dependencies);
    metrics.status_distribution = calculateStatusDistribution(dependencies);

    return metrics;
}

std::vector<DependencyTrend> DependencyReporter::analyzeDependencyTrends(const std::vector<DependencySnapshot>& snapshots) const {
    std::vector<DependencyTrend> trends;

    if (snapshots.size() < 2) {
        return trends;
    }

    // Analyze numeric trends
    trends = analyzeNumericTrends(snapshots);

    // Analyze categorical trends
    auto categorical_trends = analyzeCategoricalTrends(snapshots);
    trends.insert(trends.end(), categorical_trends.begin(), categorical_trends.end());

    return trends;
}

std::vector<std::string> DependencyReporter::generateRecommendations(const std::vector<DependencyInfo>& dependencies) const {
    std::vector<std::string> recommendations;

    int outdated_count = 0;
    int security_issues_count = 0;
    int low_compatibility_count = 0;

    for (const auto& dep : dependencies) {
        if (dep.status == "outdated") {
            outdated_count++;
            if (!dep.available_version.empty()) {
                recommendations.push_back("Update " + dep.name + " from " + dep.version +
                                        " to " + dep.available_version);
            }
        }

        if (!dep.security_issues.empty()) {
            security_issues_count++;
        }

        if (dep.compatibility_score > 0 && dep.compatibility_score < 70) {
            low_compatibility_count++;
        }
    }

    // General recommendations
    if (outdated_count > 0) {
        recommendations.push_back("Review and update " + std::to_string(outdated_count) +
                                " outdated dependencies");
    }

    if (security_issues_count > 0) {
        recommendations.push_back("Address " + std::to_string(security_issues_count) +
                                " security issues across dependencies");
    }

    if (low_compatibility_count > 0) {
        recommendations.push_back("Investigate " + std::to_string(low_compatibility_count) +
                                " dependencies with low compatibility scores");
    }

    if (recommendations.empty()) {
        recommendations.push_back("All dependencies are up-to-date and compatible");
    }

    return recommendations;
}

std::vector<std::string> DependencyReporter::identifySecurityIssues(const std::vector<DependencyInfo>& dependencies) const {
    std::vector<std::string> security_issues;

    for (const auto& dep : dependencies) {
        if (!dep.security_issues.empty()) {
            for (const auto& issue : dep.security_issues) {
                security_issues.push_back(dep.name + ": " + issue);
            }
        }
    }

    return security_issues;
}

