bool DependencyReporter::exportReportToFile(const std::vector<DependencyInfo>& dependencies,
                                          const std::string& file_path,
                                          const std::string& format) const {
    ExportOptions options;
    options.format = format;
    options.output_path = file_path;
    options.include_metadata = include_metadata_;
    options.include_trends = include_trends_;
    options.include_recommendations = include_recommendations_;

    return exportReportWithOptions(dependencies, options);
}

bool DependencyReporter::exportReportWithOptions(const std::vector<DependencyInfo>& dependencies,
                                                const ExportOptions& options) const {
    if (!validateExportOptions(options)) {
        return false;
    }

    std::string content;

    if (options.format == "json") {
        content = generateJSONReport(dependencies).dump(4);
    } else if (options.format == "markdown") {
        content = generateMarkdownReport(dependencies);
    } else if (options.format == "html") {
        content = generateHTMLReport(dependencies);
    } else if (options.format == "csv") {
        content = generateCSVReport(dependencies);
    } else if (!options.template_id.empty()) {
        auto it = report_templates_.find(options.template_id);
        if (it != report_templates_.end()) {
            content = generateCustomReport(dependencies, it->second);
        } else {
            return false;
        }
    } else {
        return false;
    }

    return writeToFile(content, options.output_path);
}

std::vector<std::string> DependencyReporter::getSupportedFormats() const {
    return {"json", "markdown", "html", "csv"};
}

// Template system implementation
bool DependencyReporter::loadTemplate(const std::string& template_id, const std::string& template_content) {
    if (!validateTemplate(template_content)) {
        return false;
    }

    report_templates_[template_id] = template_content;
    return true;
}

bool DependencyReporter::saveTemplate(const std::string& template_id, const ReportTemplate& template_info) {
    if (!validateTemplate(template_info.template_content)) {
        return false;
    }

    report_templates_[template_id] = template_info.template_content;

    // Save to file
    std::string template_file = cache_dir_ + "/templates/" + template_id + ".template";
    return writeToFile(template_info.template_content, template_file);
}

std::string DependencyReporter::generateCustomReport(const std::vector<DependencyInfo>& dependencies,
                                                    const std::string& template_content) const {
    auto report = generateDependencyReport(dependencies);
    return renderTemplate(template_content, dependencies, report);
}

// Filtering and sorting implementation
std::vector<DependencyInfo> DependencyReporter::filterDependencies(const std::vector<DependencyInfo>& dependencies,
                                                                  const std::string& field,
                                                                  const std::string& value) const {
    std::vector<DependencyInfo> filtered;

    for (const auto& dep : dependencies) {
        if (field == "name" && dep.name == value) {
            filtered.push_back(dep);
        } else if (field == "status" && dep.status == value) {
            filtered.push_back(dep);
        } else if (field == "license" && dep.license == value) {
            filtered.push_back(dep);
        } else if (field == "source_type" && dep.source_type == value) {
            filtered.push_back(dep);
        }
    }

    return filtered;
}

std::vector<DependencyInfo> DependencyReporter::sortDependencies(const std::vector<DependencyInfo>& dependencies,
                                                                const std::string& field,
                                                                bool ascending) const {
    auto sorted = dependencies;

    std::sort(sorted.begin(), sorted.end(),
        [field, ascending](const DependencyInfo& a, const DependencyInfo& b) {
            if (field == "name") {
                return ascending ? a.name < b.name : a.name > b.name;
            } else if (field == "version") {
                return ascending ? a.version < b.version : a.version > b.version;
            } else if (field == "status") {
                return ascending ? a.status < b.status : a.status > b.status;
            } else if (field == "compatibility_score") {
                return ascending ? a.compatibility_score < b.compatibility_score :
                                 a.compatibility_score > b.compatibility_score;
            }
            return false;
        });

    return sorted;
}

std::vector<DependencyInfo> DependencyReporter::searchDependencies(const std::vector<DependencyInfo>& dependencies,
                                                                  const std::string& query) const {
    std::vector<DependencyInfo> results;
    std::string lower_query = query;
    std::transform(lower_query.begin(), lower_query.end(), lower_query.begin(), ::tolower);

    for (const auto& dep : dependencies) {
        std::string lower_name = dep.name;
        std::string lower_desc = dep.description;
        std::transform(lower_name.begin(), lower_name.end(), lower_name.begin(), ::tolower);
        std::transform(lower_desc.begin(), lower_desc.end(), lower_desc.begin(), ::tolower);

        if (lower_name.find(lower_query) != std::string::npos ||
            lower_desc.find(lower_query) != std::string::npos) {
            results.push_back(dep);
        }
    }

    return results;
}

