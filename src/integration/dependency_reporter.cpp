std::string DependencyReporter::renderTemplate(const std::string& template_content,
                                              const std::vector<DependencyInfo>& dependencies,
                                              const DependencyReport& report) const {
    std::string rendered = template_content;

    // Replace simple variables
    std::map<std::string, std::string> variables = {
        {"report_id", report.report_id},
        {"generated_timestamp", report.generated_timestamp},
        {"total_dependencies", std::to_string(report.total_dependencies)},
        {"active_dependencies", std::to_string(report.active_dependencies)},
        {"outdated_dependencies", std::to_string(report.outdated_dependencies)},
        {"content", "Generated report content"}
    };

    rendered = replaceTemplateVariables(rendered, variables);

    return rendered;
}

std::string DependencyReporter::replaceTemplateVariables(const std::string& content,
                                                        const std::map<std::string, std::string>& variables) const {
    std::string result = content;

    for (const auto& [key, value] : variables) {
        std::string placeholder = "{{" + key + "}}";
        size_t pos = result.find(placeholder);
        while (pos != std::string::npos) {
            result.replace(pos, placeholder.length(), value);
            pos = result.find(placeholder, pos + value.length());
        }
    }

    return result;
}

std::vector<DependencyTrend> DependencyReporter::analyzeNumericTrends(const std::vector<DependencySnapshot>& snapshots) const {
    std::vector<DependencyTrend> trends;

    if (snapshots.size() < 2) return trends;

    // Analyze total dependencies trend
    DependencyTrend total_trend;
    total_trend.metric_name = "total_dependencies";
    total_trend.data_points.resize(snapshots.size());

    for (size_t i = 0; i < snapshots.size(); ++i) {
        total_trend.data_points[i] = static_cast<double>(snapshots[i].total_dependencies);
    }

    double slope = calculateTrendSlope(total_trend.data_points);
    total_trend.change_value = slope;
    total_trend.trend_direction = slope > 0.1 ? "increasing" :
                                  slope < -0.1 ? "decreasing" : "stable";

    trends.push_back(total_trend);

    return trends;
}

